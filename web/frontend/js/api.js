// ================================================
//  BACKEND API
//  Point this at your deployed backend. For local dev with the Flask
//  server (backend/app.py) running, use 'http://localhost:5000'.
// ================================================
const API_BASE = 'http://localhost:5000';

async function postForm(path, data) {
  const res = await fetch(API_BASE + path, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(data),
  });
  const body = await res.json().catch(() => ({}));
  if (!res.ok || !body.ok) {
    throw new Error(body.error || 'Error de servidor');
  }
  return body;
}

// "Descargar calendario" serves the .ics generated by the backend.
document.getElementById('calendarDownload').href = API_BASE + '/api/events.ics';
